/** Rule options R1 to R8 (cahier des charges §2.2). */
export const RoomOptionsSchema = z.strictObject({
  two_transparent: z.boolean(),
  jack_commands: z.boolean(),
  jack_wild: z.boolean(),
  ace_skips: z.boolean(),
  seven_draw_two: z.boolean(),
  joker_draw_four: z.boolean(),
  joker_wild: z.boolean(),
  allow_multiples: z.boolean(),
}) satisfies z.ZodType<RoomOptions>;

/**
 * Fee rule (specification des jetons §6): from `min` to `max` in steps of `step`.
 * The values come from `app_config` (`fees.min`, `fees.max`, `fees.step`).
 */
export function isValidFee(fee: number, rule: { min: number; max: number; step: number }): boolean {
  return (
    Number.isInteger(fee) &&
    fee >= rule.min &&
    fee <= rule.max &&
    (fee - rule.min) % rule.step === 0
  );
}

export type RoomType = z.infer<typeof RoomTypeSchema>;
export type RoomStatus = z.infer<typeof RoomStatusSchema>;
